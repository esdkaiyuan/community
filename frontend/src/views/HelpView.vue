    <section>
      <h2>十八、常见问题</h2>
      <p>
        以下问题按出现频率排列，每条都给出可直接执行的步骤。若仍无效，再走页末反馈渠道。
      </p>
      <h3>收不到邮箱验证码怎么办</h3>
      <p>
        先核对邮箱拼写，再检查垃圾邮件与广告分类。同一邮箱 60 秒内只能发送一次，冷却期内重复点击没有意义。验证码 5 分钟内有效，超时需重新获取。企业邮箱可能延迟，换网络或隔几分钟再试；持续收不到时，通过反馈渠道提供邮箱域名与时间，不要粘贴验证码。
      </p>
      <h3>提示验证码发送太频繁</h3>
      <p>
        这是 60 秒冷却或更长时间的风控限制。停止点击，等待按钮恢复可用再发送。若短时间内多次触发，等待时间可能被延长，通常数分钟后恢复。不要在多个标签页同时请求。
      </p>
      <h3>验证码正确却提示无效</h3>
      <p>
        最常见的原因是验证码已超过 5 分钟，或你填写的是上一条邮件里的旧码。确认当前邮件的时间，重新获取一次；同时检查是否误输入空格或漏掉字符。
      </p>
      <h3>注册按钮提示「请先阅读并同意」</h3>
      <p>
        注册页要求先勾选协议确认框，未勾选时不会提交注册请求。阅读<router-link to="/terms">《用户协议》</router-link>、<router-link to="/privacy">《隐私政策》</router-link>与<router-link to="/community-rules">《平台管理条例》</router-link>后，勾选「我已阅读并同意」，再点击「注册并加入」。三个链接会在新标签打开，读完回来勾选即可，表单里已填的内容不会丢失。
      </p>
      <h3>登录后很快失效</h3>
      <p>
        修改或重置密码会让所有旧凭证失效；清除浏览器数据、切换无痕模式、更换浏览器也会退出登录。重新登录即可。若刚登录就失效，检查系统时间是否准确、浏览器是否允许保存站点数据。
      </p>
      <h3>忘记密码怎么办</h3>
      <p>
        在<router-link to="/login">登录页</router-link>点击「忘记密码」，用注册邮箱接收验证码，验证后设置新密码。新密码不要与旧密码相同。重置成功后所有设备需要重新登录，这是正常的安全设计。
      </p>
      <h3>发布按钮一直是灰色</h3>
      <p>
        逐项检查必填字段：标题是否在 4 到 60 个字符之间，介绍是否在 20 到 2000 个字符之间，分类是否已选择。任一条件不满足，按钮可能保持不可用。若字段都正确仍无法提交，刷新页面或更换浏览器再试。
      </p>
      <h3>标题或介绍超出长度限制</h3>
      <p>
        标题上限 60 个字符，介绍上限 2000 个字符。中英文、数字与标点通常都计入长度，粘贴长文时很容易超限。先精简到核心信息，把细节放到评论区补充。
      </p>
      <h3>标签加不进去</h3>
      <p>
        标签最多 5 个，单个不超过 12 个字符，需要按回车添加。已达到上限时先删除一个；单个过长时换一个更短的词；输入法拦截回车时，先确认候选词再按一次回车。
      </p>
      <h3>封面上传失败</h3>
      <p>
        依次检查体积是否超过 5MB、格式是否为 JPG、PNG、WebP、GIF 之一、文件是否损坏、网络是否稳定。把图片压缩到几百 KB 通常能解决大多数问题。若使用图片地址，确认链接可公开访问且不是网盘分享页。
      </p>
      <h3>仓库地址提示格式错误</h3>
      <p>
        仓库地址必须以 http 或 https 开头，长度不超过 255 个字符。不要省略协议头，不要带多余空格，也不要把本地路径或命令行指令填进去。确认链接在浏览器中可以直接打开。
      </p>
      <h3>截止日期填不进去</h3>
      <p>
        格式必须是 YYYY-MM-DD，例如 2026-12-31。写成 2026/12/31、2026年12月31日或只填月份都不符合要求。该字段可选，不确定时留空。
      </p>
      <h3>如何修改项目的加密级别</h3>
      <p>
        进入项目编辑页，调整加密级别后保存。从隐藏完整详情改为仅隐藏仓库地址，介绍与标签会重新公开；改为不加密则全部公开。编辑时密码留空表示沿用原密码，只有想更换密码时才填写新的。
      </p>
      <h3>忘记加密项目的访问密码</h3>
      <p>
        平台不保存明文密码，无法代为找回。发起人可在编辑页设置新密码，或删除后重新发布；其他人只能向发起人索取。若项目已改为公开，就不再需要密码。
      </p>
      <h3>为什么别人看不到我的项目</h3>
      <p>
        先确认加密级别。设为隐藏完整详情时，别人只能看到标题、封面与分类；设为仅隐藏仓库地址时，仓库不可见。其次确认对方是否登录、链接是否正确、项目是否已被删除。也检查项目是否因违规被处理。
      </p>
      <h3>如何参与或退出项目</h3>
      <p>
        登录后在详情页点击参与即可加入，发起人会收到通知。参与者如需退出，可在详情页取消参与。发起人不能退出自己的项目，只能删除项目或先完成交接。
      </p>
      <h3>发起人能退出自己的项目吗</h3>
      <p>
        不能。发起人会自动成为参与者并被固定在项目中，这是为了避免出现无人负责的项目。如果确实要结束，只能删除项目；删除前建议先在评论区说明。
      </p>
      <h3>评论发不出去</h3>
      <p>
        检查是否超过 500 字、是否仍处于登录状态、网络是否正常、是否连续发表过多条触发限制、内容是否命中规则。页面通常会给提示，按提示修改即可。
      </p>
      <h3>@ 没有高亮也没有通知</h3>
      <p>
        确认用户名拼写与对方当前用户名完全一致，@ 与用户名之间没有空格。用户名修改后旧的写法会失效，最好从对方主页复制。写在代码块里的 @ 不会被解析。
      </p>
      <h3>点击通知没有跳到对应位置</h3>
      <p>
        目标评论或项目可能已被删除；项目改成加密后需要先解锁；网络慢时刷新重试。若只有单条通知异常，提供通知时间与项目标题给反馈渠道。
      </p>
      <h3>收藏不见了</h3>
      <p>
        确认登录的是收藏时用的账号，确认项目未被删除。清除浏览器数据只会退出登录，不会删除账号内的收藏，重新登录即可看到。若条目存在但打不开，多半是项目改为加密或调整了可见范围。
      </p>
      <h3>如何删除评论或项目</h3>
      <p>
        评论可在自己评论旁点击删除，确认后生效；删除根评论会连同其下回复一起删除。项目在详情页底部删除，只有发起人可操作。两者都不可恢复，操作前先备份需要保留的文字。
      </p>
      <h3>如何修改邮箱或注销账号</h3>
      <p>
        这两项需要身份校验，页面不提供自助入口。通过页末反馈渠道提交申请，说明账号邮箱与办理事项。不要在公开 Issue 里粘贴密码、验证码或身份证信息。
      </p>
      <h3>遇到 429 或操作过于频繁</h3>
      <p>
        这是频率限制，不是账号被封。停止重试，等待几分钟后再操作。登录、注册、发验证码、找回密码、解锁加密项目都会触发限制，短时间多标签页并发请求更容易命中。
      </p>
      <h3>页面空白或一直加载</h3>
      <p>
        先刷新，再检查网络，接着清除缓存、关闭扩展、换浏览器。多个页面同时异常时，可能是服务短时不可用，稍后再试。持续存在时，反馈时附上浏览器版本、页面地址与发生时间。
      </p>
