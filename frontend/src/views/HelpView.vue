        <li>注册成功后按页面提示进入登录或直接进入站内，若未自动登录，用刚设置的密码登录即可。</li>
      </ol>
      <h3>验证码的三条规则</h3>
      <ul>
        <li><strong>60 秒冷却：</strong>同一邮箱发送一次后，必须等满 60 秒才能再次发送。反复点击不会加速，只会让按钮一直处于冷却状态。</li>
        <li><strong>5 分钟有效：</strong>从发出时开始计时，超过 5 分钟即失效，需要重新获取，旧验证码不能用。</li>
        <li><strong>敏感接口有频率限制：</strong>短时间内反复请求发送、登录、找回密码等操作，可能返回 429 或提示「操作过于频繁」，此时只能等待，继续尝试只会延长限制时间。</li>
      </ul>
      <h3>收不到验证码的排查顺序</h3>
      <ol>
        <li>确认邮箱拼写没有少字符、没有把常见域名写错。</li>
        <li>检查垃圾邮件、广告邮件与「推广」分类，验证码邮件有时会被自动归类。</li>
        <li>等待 60 秒后再点一次发送，避免在冷却期内反复点击。</li>
        <li>换一个网络环境重试，部分企业邮箱或校园网会延迟接收外部邮件。</li>
        <li>若多次尝试仍收不到，隔一段时间再试，或通过页末反馈渠道说明邮箱域名与大致时间，不要粘贴验证码本身。</li>
      </ol>
      <div class="doc-note">
        <strong>验证码只属于你自己。</strong>
