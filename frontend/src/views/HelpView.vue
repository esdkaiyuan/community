      <h2>四、浏览、搜索、筛选与排序</h2>
      <p>
        首页是发现项目的主场景，提供了搜索、分类、热门标签、编辑推荐与四种排序。理解它们各自的用途，比盲目翻页效率高得多。
      </p>
      <h3>首页由哪些部分组成</h3>
      <ul>
        <li><strong>搜索框：</strong>按关键词匹配项目，适合你已经知道想找什么。</li>
        <li><strong>分类：</strong>技术开发、设计创意、产品/运营、内容创作、硬件/物联网、研究学习、开源专区、公益/社会创新，共八类。</li>
        <li><strong>热门标签：</strong>平台汇总的高频标签，适合不知道从哪下手时先逛一圈。</li>
        <li><strong>编辑推荐：</strong>由平台挑选的项目，通常描述完整、方向清晰，适合作为写作参考。</li>
        <li><strong>排序：</strong>最新、最热、参与最多、本周热门，决定列表的先后顺序。</li>
      </ul>
      <h3>搜索的实用技巧</h3>
      <ol>
        <li>用两到四个关键词，比如「硬件 传感器 开源」，比整句描述更容易命中。</li>
        <li>中英文都试一次，项目标题可能使用英文术语或缩写。</li>
        <li>换同义词再搜，例如「物联网」与「IoT」、「招募」与「找伙伴」。</li>
        <li>搜索结果为空时，先减少关键词，再回到分类浏览。</li>
      </ol>
      <h3>四种排序的差别</h3>
      <ul>
        <li><strong>最新：</strong>按发布时间倒序，适合观察平台最近出现的新方向。</li>
        <li><strong>最热：</strong>按整体热度排序，适合看已经被验证有讨论度的项目。</li>
        <li><strong>参与最多：</strong>按参与者数量排序，适合寻找已经形成小团队的项目。</li>
        <li><strong>本周热门：</strong>只统计近 7 天的活跃度，其中参与计 3 分、评论计 2 分、点赞计 1 分。它反映的是「这周谁在动」，而不是历史累计。</li>
      </ul>
      <p>
        「本周热门」的计分方式解释了一个常见困惑：一个老项目如果这周没人参与、评论、点赞，就会从前排掉下去；一个刚发布但讨论热烈的新项目可以迅速上来。想验证自己的项目是否被看到，可以观察它在这几个维度上的变化。
      </p>
      <h3>组合筛选的建议</h3>
      <ul>
        <li>先用分类框定方向，再用标签收窄，最后用排序决定先看谁。</li>
        <li>如果列表突然变空，通常是条件叠得太窄，逐个取消即可恢复。</li>
        <li>编辑推荐与排序是不同维度，前者是人工挑选，后者是规则排序，不必强行比较。</li>
      </ul>
      <h3>列表卡片怎么看</h3>
      <p>
        卡片上通常呈现标题、分类、标签、封面与参与者规模等摘要信息。标题决定你要不要点开，标签决定它属于哪个细分方向，参与者数量提示它是否已经有伙伴。封面只是氛围，不构成质量担保，判断项目仍要回到介绍本身。
      </p>
      <div class="doc-note">
        <strong>筛选不等于审核。</strong>
        能被搜索到、能被推荐，只说明项目符合展示条件，不代表平台核实过内容真实性。合作前请自行判断，必要时要求对方提供可验证的材料。
