        <li>选择明暗模式。</li>
        <li>选择强调色。</li>
        <li>返回任意页面确认效果，无需刷新。</li>
      </ol>
      <h3>偏好保存在哪里</h3>
      <p>
        外观偏好只保存在当前浏览器，不写入账号。这意味着换设备、换浏览器、使用无痕模式，都会回到默认外观；清除浏览器数据后同样会恢复默认。如果你在多台设备上使用，需要分别设置一次。
