      <h2>五、发布项目：逐字段说明</h2>
      <p>
        发布是本站最核心的动作。表单字段不多，但每个字段都有明确限制，提前知道规则可以一次提交成功。
      </p>
      <h3>字段限制一览</h3>
      <ul>
        <li><strong>标题：</strong>4 至 60 个字符。少于 4 个字符信息量不足，超过 60 个字符会被截断或拒绝。</li>
        <li><strong>介绍：</strong>20 至 2000 个字符。20 个字符是最低门槛，实际写作建议至少两三百字，把背景、目标与需求说清楚。</li>
        <li><strong>分类：</strong>必填，从八个分类中选一个最贴近的。</li>
        <li><strong>标签：</strong>最多 5 个，单个不超过 12 个字符，按回车添加。</li>
        <li><strong>封面：</strong>不超过 5MB，支持 JPG、PNG、WebP、GIF，可以本地上传，也可以填写图片地址。</li>
        <li><strong>仓库地址：</strong>可选，须以 http 或 https 开头，长度不超过 255 个字符。</li>
        <li><strong>截止日期：</strong>可选，格式为 YYYY-MM-DD，例如 2026-12-31。</li>
      </ul>
      <h3>提交步骤</h3>
      <ol>
        <li>登录后点击页头右上角的「发布项目」，或直接打开<router-link to="/publish">发布页</router-link>。</li>
        <li>填写标题，控制在 4 到 60 个字符之间，尽量具体。</li>
        <li>填写介绍，说明背景、目标、当前进度、需要的角色与参与方式。</li>
        <li>选择分类，添加标签，每个标签按回车确认，最多 5 个。</li>
        <li>按需上传封面或填写图片地址，按需填写仓库地址与截止日期。</li>
        <li>如果项目需要保密，在发布前设置加密级别与访问密码。</li>
        <li>检查一遍，确认无误后提交。成功后按页面提示进入项目详情页。</li>
      </ol>
      <h3>发布失败怎么排查</h3>
      <ul>
        <li>先看页面提示的具体字段，多数失败都是长度、格式或必填项问题。</li>
        <li>标题不足 4 个字、介绍不足 20 个字，按钮可能保持不可用。</li>
        <li>标签超过 5 个或单个超过 12 个字，需要删除多余的再提交。</li>
        <li>仓库地址缺少 http 或 https 前缀，或带有多余空格，会被判为格式错误。</li>
        <li>截止日期写成 2026/12/31 或 2026年12月31日，都不符合 YYYY-MM-DD 要求。</li>
        <li>封面超过 5MB 或格式不在支持列表内，上传会失败。</li>
        <li>网络中断或接口限流时，页面可能提示保存失败，稍后重试，不要连续快速点击提交。</li>
      </ul>
      <div class="doc-note">
        <strong>提交前读一遍管理条例。</strong>
        标题、介绍、封面与链接都受<router-link to="/community-rules">《平台管理条例》</router-link>约束。涉及收费招募、导流交易或他人素材的，先在条例里确认边界，比发布后被处理更省事。
