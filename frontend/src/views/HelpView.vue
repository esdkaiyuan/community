      <h2>十七、移动端与浏览器兼容</h2>
      <p>
        平台按响应式设计，手机与桌面浏览器都能使用。多数显示问题来自浏览器版本、扩展插件与缓存，而不是页面本身。
      </p>
      <h3>移动端操作要点</h3>
      <ul>
        <li>发布项目时，逐个字段填写，避免在多个标签页之间来回切换导致内容丢失。</li>
        <li>上传封面优先选择相册中的图片，并在上传前确认体积不超过 5MB。</li>
        <li>标签输入后记得按回车确认，部分输入法会把回车当作换行。</li>
        <li>长评论建议先在备忘录写好再粘贴，避免误触返回导致内容清空。</li>
        <li>通知与评论的跳转在移动端同样可用，点击后会自动定位。</li>
      </ul>
      <h3>页面空白或加载失败</h3>
      <ol>
        <li>先刷新页面，排除偶发的网络抖动。</li>
        <li>检查网络是否正常，切换 Wi-Fi 与移动网络对比。</li>
        <li>清除浏览器缓存后重试，缓存过期可能导致资源加载失败。</li>
        <li>暂时关闭扩展或换一个浏览器，确认是否是插件干扰。</li>
        <li>若多个页面同时空白，稍后再试，可能是服务短时不可用。</li>
        <li>问题持续时，通过反馈渠道说明浏览器版本、页面地址与出现时间。</li>
      </ol>
      <h3>图片不显示</h3>
      <ul>
        <li>封面或头像使用外链时，链接失效会显示空白，换成本地上传即可。</li>
        <li>部分网络会拦截外部图片域名，切换网络后可能恢复。</li>
        <li>浏览器开启节省流量模式时，图片可能被延迟加载。</li>
      </ul>
      <div class="doc-note">
        <strong>不要用修改页面的方式绕过限制。</strong>
        通过开发者工具篡改前端校验提交超限内容，通常仍会被服务端拒绝；反复尝试还可能触发频率限制。
