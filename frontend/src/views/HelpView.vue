      <h2>六、把项目写清楚：标题、介绍与标签</h2>
      <p>
        平台不缺想法，缺的是让陌生人愿意停下来读完的描述。这一节不是规则，而是写法建议，你可以按自己的风格调整。
      </p>
      <h3>标题：具体胜过宏大</h3>
      <ul>
        <li>写清对象与动作，例如「校园二手书交换小程序」「面向听障用户的字幕工具」，比「一个伟大的项目」有效。</li>
        <li>把可搜索的关键词放进去，方便别人通过搜索找到你。</li>
        <li>控制在 4 到 60 个字符，留出余量，避免刚好卡在边界被截断。</li>
        <li>不要用堆砌符号、重复感叹或与内容无关的流行词。</li>
      </ul>
      <h3>介绍：用六段结构写</h3>
      <ol>
        <li><strong>一句话说明是什么：</strong>让读者在三秒内知道项目做什么。</li>
        <li><strong>为什么做：</strong>你遇到的问题、观察到的需求，或想验证的假设。</li>
        <li><strong>现在做到哪一步：</strong>想法、原型、可运行版本、已上线，诚实描述进度。</li>
        <li><strong>需要谁：</strong>具体角色与技能，例如前端、结构设计、内容运营，而不是笼统的「志同道合的人」。</li>
        <li><strong>怎么加入：</strong>在评论区说明，或直接参与项目，给出你希望的沟通方式。</li>
        <li><strong>时间与边界：</strong>预计周期、投入强度、是否涉及代码开源与成果归属。</li>
      </ol>
      <h3>两个对照写法</h3>
      <p>
        第一种是常见但低效的写法：「我有一个改变世界的想法，寻找志同道合的伙伴一起做，感兴趣的联系我。」读者无法判断要做什么、需要谁、投入多少。
      </p>
      <p>
        第二种是可执行的写法：「我在做一个面向社区图书馆的借阅管理工具，目前完成借还书主流程的原型，用的是开源技术栈。接下来两个月需要一位熟悉移动端开发的同学一起做扫码借书，每周能投入五小时左右。原型说明与仓库地址在下方，愿意参与的同学可以在评论区留下技能与可投入时间。」两段话的信息密度差异，决定了别人是否回复。
      </p>
      <h3>标签策略</h3>
      <ul>
        <li>用三到五个标签，宽泛与具体各占一半，例如「开源」加「数据可视化」。</li>
        <li>每个标签不超过 12 个字符，别把一整句话塞进标签。</li>
        <li>按回车逐个添加，添加后确认没有多余空格。</li>
        <li>标签是检索入口，不是情绪表达，避免「求关注」「急」这类词。</li>
      </ul>
      <h3>分类怎么选</h3>
      <p>
        分类只有八个，选最贴近项目主要产出的那个：写代码与工具选技术开发，做界面与视觉选设计创意，偏运营与商业选产品/运营，做内容与媒体选内容创作，涉及硬件与设备选硬件/物联网，偏学习与研究选研究学习，纯开源项目选开源专区，公益导向选公益/社会创新。跨领域项目选一个主分类，其余方向用标签表达。
      </p>
      <h3>常见减分项</h3>
      <ul>
        <li>通篇口号，没有可验证的进度与具体需求。</li>
        <li>介绍里夹带联系方式、收款方式或外部交易引导。</li>
        <li>封面与内容无关，或使用来源不明的图片。</li>
        <li>标签堆满热门词，与项目实际方向无关。</li>
        <li>截止日期设在过去，或与介绍里的周期互相矛盾。</li>
      </ul>
      <div class="doc-note">
        <strong>写作也是筛人。</strong>
        清楚的介绍会自动过滤掉不合适的人，也会让真正合适的伙伴更快做决定。花二十分钟把介绍写完整，通常比之后解释十遍更省时间。
