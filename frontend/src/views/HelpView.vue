        <li><strong>跟随系统：</strong>由操作系统或浏览器的配色偏好决定，系统切换时页面同步变化。</li>
      </ul>
      <h3>四种强调色</h3>
      <ul>
        <li>电光青，默认配色，偏冷，辨识度高。</li>
        <li>静谧蓝，更沉稳，适合长时间阅读。</li>
        <li>苔原绿，偏自然，与平台的绿色基调接近。</li>
        <li>鸢尾紫，偏柔和，适合喜欢低对比强调的人。</li>
