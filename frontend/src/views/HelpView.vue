      <h2>八、加密项目完整指南</h2>
      <p>
        有些项目在成形前不适合完全公开，例如还涉及未公开的合作方、尚未申请的知识产权，或只是想让小范围的人先看到。平台提供加密项目来解决这类需求，它不是权限系统，而是「凭密码查看」的展示控制。
      </p>
      <h3>三档加密级别</h3>
      <ul>
        <li><strong>不加密：</strong>项目完整公开，任何人都能看到介绍、标签、仓库地址与共创伙伴。</li>
        <li><strong>仅隐藏仓库地址：</strong>其余内容照常展示，只有仓库地址被隐藏。适合代码尚未整理好、暂时不希望被直接查看的情况。</li>
        <li><strong>隐藏完整详情：</strong>介绍、标签、仓库地址与共创伙伴都会被隐藏，但标题、封面与分类仍然可见。适合只有方向可以公开、细节需要保密的项目。</li>
      </ul>
      <h3>创建加密项目</h3>
      <ol>
        <li>按正常流程进入<router-link to="/publish">发布页</router-link>，填写标题、介绍、分类等字段。</li>
        <li>在加密设置中选择合适的级别，不要默认选最高档，按实际保密需求决定。</li>
        <li>设置访问密码，长度在 6 到 64 位之间。</li>
        <li>确认标题与封面在加密后仍然对外可见，避免把不该公开的信息放进标题或封面。</li>
        <li>提交发布。此时项目在列表中仍会出现，但详情按所选级别受限。</li>
      </ol>
      <h3>访问密码的规则</h3>
      <ul>
        <li>长度 6 到 64 位，建议使用字母、数字与符号混合，而不是纯数字。</li>
        <li>平台不保管明文密码，服务端无法替你还原，因此忘记后不能通过客服找回。</li>
        <li>密码用于解锁查看，不是账号密码，不要与登录密码相同。</li>
        <li>把密码通过站外可信渠道告诉合作对象，不要在公开评论区直接贴出。</li>
      </ul>
      <h3>同一账号只能保留一个加密项目</h3>
      <p>
        每个账号在同一时间最多只能有一个加密项目。已经有一个加密项目时再创建加密项目，会被拒绝。想再建一个，需要先处理已有的那个：把它改为公开，或者删除。改为公开或删除完成后，就可以创建新的加密项目。这条限制是为了避免大量不可见内容堆积，难以核查。
      </p>
      <h3>谁能看到什么</h3>
      <ul>
        <li><strong>发起人：</strong>始终能看到自己项目的完整内容，不需要每次输入密码。</li>
        <li><strong>其他人：</strong>需要输入正确的访问密码解锁，解锁后才能看到被隐藏的部分。</li>
        <li><strong>未登录访客：</strong>同样受加密级别限制，看不到被隐藏的字段。</li>
        <li><strong>隐藏完整详情时：</strong>标题、封面、分类仍可见，介绍、标签、仓库地址与共创伙伴不可见。</li>
      </ul>
      <h3>解锁流程</h3>
      <ol>
        <li>打开加密项目详情页，页面会提示需要密码。</li>
        <li>输入发起人提供的访问密码，注意区分大小写与前后空格。</li>
        <li>密码正确后，被隐藏的字段会展开显示。</li>
        <li>连续输错会触发频率限制，需要等待一段时间再试。</li>
        <li>若确认密码无误却无法解锁，先确认项目是否已被发起人改为公开或修改了密码。</li>
      </ol>
      <h3>编辑加密项目</h3>
      <ul>
        <li>发起人可在编辑页修改标题、介绍、标签、封面等字段。</li>
        <li>编辑时密码可以留空，留空表示沿用原密码；只有想更换密码时才需要填写新的。</li>
        <li>修改加密级别时，要清楚升级与降级分别暴露什么内容。从隐藏完整详情改为仅隐藏仓库地址，介绍会重新公开。</li>
      </ul>
      <h3>改为公开</h3>
      <ol>
        <li>进入项目编辑页，把加密级别改为不加密。</li>
        <li>确认密码字段是否需要清空，按页面提示处理。</li>
        <li>保存后，项目完整内容对所有访客可见。</li>
        <li>改为公开后，该账号的加密项目名额被释放，可以创建新的加密项目。</li>
      </ol>
      <h3>删除加密项目</h3>
      <p>
        删除操作在项目详情页底部，需要确认。删除后项目不再展示，名额同样被释放。删除不可恢复，密码也会一起消失，若你还想保留内容，先自行复制介绍与仓库地址。
      </p>
      <h3>忘记访问密码怎么办</h3>
      <ul>
        <li>发起人自己也忘记密码时，平台无法代为找回，因为服务端不保存明文。</li>
        <li>可行的做法是编辑项目并设置一个新密码，或删除后重新发布。</li>
        <li>其他人忘记密码时，只能向发起人索取，平台不会向第三方透露。</li>
      </ul>
      <div class="doc-note">
        <strong>加密保护的是展示，不是协作安全。</strong>
        拿到密码的人可以自行复制、转发内容。请不要在加密项目里放置身份证号、住址、未公开的个人信息或商业机密原文。
