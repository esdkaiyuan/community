      <h3>设置没有生效</h3>
      <ul>
        <li>确认浏览器没有禁用本地存储，禁用后偏好无法保存。</li>
        <li>确认没有开启强制深色或强制高对比的浏览器扩展。</li>
        <li>系统级的「减少动态效果」会改变部分过渡动画，但不会改变配色。</li>
        <li>清除数据后需要重新选择，这是预期行为，不是故障。</li>
      </ul>
