      <h3>注册前的准备</h3>
      <ul>
        <li>一个你能正常收信的邮箱，注册后补填或换绑都需要通过反馈渠道，所以尽量使用长期在用的邮箱。</li>
        <li>一个足够长的密码，至少不要与邮箱、其他网站重复；密码规则以注册页的实时提示为准。</li>
        <li>几分钟时间读完<router-link to="/terms">《用户协议》</router-link>、<router-link to="/privacy">《隐私政策》</router-link>与<router-link to="/community-rules">《平台管理条例》</router-link>。注册页要求主动勾选确认，未勾选不会提交注册。</li>
        <li>稳定的网络环境。频繁切换网络或代理，容易触发敏感接口的频率限制。</li>
      </ul>
      <h3>注册步骤</h3>
      <ol>
        <li>打开<router-link to="/register">注册页</router-link>，填写用户名与邮箱地址。</li>
        <li>点击「发送验证码」，等待邮件到达。同一邮箱两次发送之间有 60 秒冷却，按钮会在此期间不可用。</li>
        <li>在邮件中找到验证码，验证码有效期为 5 分钟，过期需要重新获取。</li>
        <li>填写验证码与密码，并确认两次输入的密码一致。</li>
        <li>阅读并勾选协议确认框。三个书名号链接会在新标签打开，读完回来勾选即可，已填内容不会丢失。</li>
