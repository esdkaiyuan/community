      <h2>三、登录、找回密码与登录状态</h2>
      <p>
        平台提供两种登录方式：密码登录与验证码登录。两者进入的是同一个账号，选哪个取决于你当前更方便提供什么。
      </p>
      <h3>两种登录方式怎么选</h3>
      <ul>
        <li><strong>密码登录：</strong>适合固定设备、日常使用。输入邮箱与密码即可，注意大小写与输入法状态。</li>
        <li><strong>验证码登录：</strong>适合临时设备、忘记密码或不想在公共电脑上输入密码的场景。仍受 60 秒冷却与 5 分钟有效期约束。</li>
      </ul>
      <h3>密码登录步骤</h3>
      <ol>
        <li>打开<router-link to="/login">登录页</router-link>，选择密码登录。</li>
        <li>填写注册时使用的邮箱与密码。</li>
        <li>确认没有多余空格，尤其是手机输入法自动补的空格。</li>
        <li>提交后若提示账号或密码错误，先核对邮箱，再尝试验证码登录确认账号状态。</li>
      </ol>
      <h3>验证码登录步骤</h3>
      <ol>
        <li>在登录页切换到验证码登录。</li>
        <li>填写邮箱并发送验证码，等待邮件。</li>
        <li>在 5 分钟内填入验证码完成登录。</li>
        <li>若长时间未收到，按上一节的排查顺序处理，不要连续点击发送。</li>
      </ol>
      <h3>忘记密码怎么办</h3>
      <ol>
        <li>在<router-link to="/login">登录页</router-link>点击「忘记密码」，进入找回流程。</li>
        <li>填写注册邮箱并获取验证码，同样遵守 60 秒冷却与 5 分钟有效。</li>
        <li>输入验证码后设置新密码，新密码不要与旧密码相同。</li>
        <li>提交成功后，此前签发的登录凭证全部失效，包括其他设备上的登录状态，需要用新密码重新登录。</li>
      </ol>
      <div class="doc-note">
        <strong>改密码等于全端下线。</strong>
        这是有意的安全设计：一旦密码可能泄露，旧凭证不应继续有效。改完密码后发现自己「被退出登录」属于正常现象，重新登录即可。
      </div>
      <h3>登录状态为什么会失效</h3>
      <ul>
        <li>修改或重置了密码，旧凭证被统一作废。</li>
        <li>清除了浏览器数据、使用了无痕模式，或更换了浏览器与设备。</li>
        <li>浏览器禁用了必要的存储能力，登录状态无法保存。</li>
        <li>系统时间与实际时间偏差过大，部分校验会失败。</li>
      </ul>
      <h3>遇到频率限制</h3>
      <p>
        登录、注册、找回密码、发送验证码、解锁加密项目等敏感接口都设有限制。触发后页面会提示等待或直接返回 429。此时正确的做法是停止重试，等待数分钟后再操作；频繁刷新与更换账号尝试，只会让限制持续更久。若确认自己没有异常操作却被持续限制，可通过反馈渠道说明时间与操作类型。
      </p>
      <h3>登录安全习惯</h3>
      <ul>
        <li>不要在公共电脑上勾选长期保持登录，用完主动退出。</li>
        <li>不要把密码保存在聊天记录、备忘录或截图里。</li>
        <li>发现陌生登录记录或异常失败尝试，立即修改密码，并按<router-link to="/security">账号安全</router-link>页的提示检查。</li>
      </ul>
