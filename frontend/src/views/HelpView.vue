      <h2>七、封面上传与图片问题</h2>
      <p>
        封面是列表里最先被看到的部分，它不决定项目质量，却影响点击率。上传本身不复杂，多数失败都来自体积、格式与图片地址三个方向。
      </p>
      <h3>封面支持什么</h3>
      <ul>
        <li>体积不超过 5MB。超过这个上限，无论格式是否正确都无法上传。</li>
        <li>格式支持 JPG、PNG、WebP、GIF 四种。</li>
        <li>两种来源：从本地选择文件上传，或直接填写一个可公开访问的图片地址。</li>
      </ul>
      <h3>上传步骤</h3>
      <ol>
        <li>在发布页或编辑页找到封面区域，选择本地上传或填写图片地址。</li>
        <li>本地选择一张符合格式与体积要求的图片，等待上传完成。</li>
        <li>确认封面预览正常显示，没有被拉伸或裁切到只剩一角。</li>
        <li>填写其余字段后一并提交，避免先提交再反复编辑。</li>
        <li>若上传失败，先看提示，再按下面的排查顺序处理。</li>
      </ol>
      <h3>选图的实用建议</h3>
      <ul>
        <li>优先横版构图，接近十六比九的比例更稳妥，竖图与超长图在部分位置会被压缩。</li>
        <li>把关键信息放在画面中央，边缘留出余量，避免不同展示尺寸下被裁掉。</li>
        <li>封面里不要塞满小字，列表里通常只有很小的展示面积，文字会糊成一片。</li>
        <li>颜色对比要够，深色背景配浅色主体或反过来，缩略状态下更容易辨认。</li>
        <li>示意图、界面截图、手绘草图都可以，只要与项目内容相关。</li>
      </ul>
      <h3>填写图片地址的注意事项</h3>
      <ul>
        <li>地址必须能被公开访问，需要登录才能打开的链接通常会显示破图。</li>
        <li>优先使用以 http 或 https 开头的直链，不要填网页地址或网盘分享页地址。</li>
        <li>部分图床有防盗链策略，页面里能看，站内引用时会被拒绝，换一个图床即可。</li>
        <li>地址失效、图片被删除或权限被改成私有，都会导致封面变成空白。</li>
      </ul>
      <h3>上传失败的常见原因</h3>
      <ul>
        <li><strong>超过 5MB：</strong>先压缩再上传，手机相册里的原图常常有十几兆。</li>
        <li><strong>格式不支持：</strong>HEIC、SVG、TIFF 等格式不在支持列表内，转成 JPG 或 PNG 再试。</li>
        <li><strong>扩展名与实际格式不一致：</strong>把其他格式直接改名成 JPG 并不能通过校验，需要用工具真正转换。</li>
        <li><strong>网络中断：</strong>上传过程中断网或切后台会导致失败，换稳定网络重试。</li>
        <li><strong>图片损坏：</strong>文件本身不完整时无法解析，用看图软件打开确认后再上传。</li>
      </ul>
      <div class="doc-note">
        <strong>封面也有版权。</strong>
        使用他人的图片、截图或设计稿前，请确认授权范围；转载须注明来源与许可。来源不明的网图即使能上传，也可能在后续处理中被要求更换。
      </div>
