    <section>
      <h2>十二、评论、回复、@ 与富文本</h2>
      <p>
        评论区是协作真正开始的地方。平台采用两级结构：根评论与回复，回复不再继续嵌套。理解这个结构，能避免写完发现回复挂错位置。
      </p>
      <h3>评论区的结构</h3>
      <ul>
        <li><strong>根评论：</strong>直接针对项目发表的一级评论。</li>
        <li><strong>回复：</strong>挂在某条根评论下的二级内容，保持在同一串讨论里。</li>
        <li>回复之下不再有第三级，想继续讨论时，仍然回复同一条根评论即可。</li>
        <li>单条评论不超过 500 字。</li>
        <li>根评论每页展示 10 条，翻页查看更多。</li>
        <li>回复随所属根评论一起展示，超过 3 条时默认折叠，展开后查看全部。</li>
      </ul>
      <h3>发表评论</h3>
      <ol>
        <li>登录后打开项目详情页，滚动到评论区。</li>
        <li>在输入框写下内容，控制在 500 字以内。</li>
        <li>需要强调时用两个星号包裹文字得到加粗效果；需要展示代码时用反引号包裹行内代码，多行代码用三个反引号包裹成代码块。</li>
        <li>需要提醒特定的人时，输入 @ 加对方的真实用户名。</li>
        <li>检查无误后提交，评论会立即出现在列表中。</li>
      </ol>
      <h3>@ 提及的正确用法</h3>
      <ul>
        <li>@ 后面必须跟真实存在的用户名，拼写完全一致才会高亮并通知对方。</li>
        <li>用户名中的空格、下划线、数字都要原样输入，少一个字符就不会命中。</li>
        <li>@ 成功后对方会收到提及通知，用户名在评论中高亮显示。</li>
        <li>不要在一条评论里连续 @ 大量无关的人，这会被视为骚扰。</li>
      </ul>
      <h3>@ 没有高亮怎么排查</h3>
      <ul>
        <li>确认用户名拼写正确，最好从对方主页复制。</li>
        <li>确认 @ 与用户名之间没有多余空格或标点。</li>
        <li>确认对方账号仍然存在且用户名没有被修改。</li>
        <li>确认没有把 @ 写进代码块或反引号内，代码区域内的内容不会被解析。</li>
      </ul>
      <h3>支持的格式与不支持的格式</h3>
      <ul>
        <li>支持加粗、行内代码、代码块，以及 @ 提及的自动高亮。</li>
        <li>不支持图片、视频、表格与自定义字体，粘贴进来会变成纯文本或无法提交。</li>
        <li>不要依赖颜色与字号表达重点，它们不会生效。</li>
      </ul>
      <h3>回复与折叠</h3>
      <ul>
        <li>点击根评论下的回复入口即可在其下留言，回复会归入同一讨论串。</li>
        <li>一条根评论的回复超过 3 条时会被折叠，点击展开查看全部。</li>
        <li>回复不会单独占一页，所以长讨论请尽量在根评论里把上下文说清。</li>
      </ul>
      <h3>删除评论</h3>
      <ol>
        <li>找到自己发表的评论，点击删除入口。</li>
        <li>阅读确认框中的提示，确认要删除的是哪一条。</li>
        <li>确认后评论消失。删除根评论会连同它下面的所有回复一起删除。</li>
        <li>删除不可撤销，重要内容先自行保存。</li>
      </ol>
      <h3>从通知回到评论</h3>
      <p>
        评论、回复与提及产生的通知可以直接跳转到对应位置，并高亮相关评论。这解决了长讨论里找不到上下文的问题。若跳转后没有定位到，先确认评论是否已被删除，再刷新页面重试。
      </p>
      <div class="doc-note">
        <strong>评论是公开的。</strong>
        写下的内容所有人都能看到，也可能被截图转发。涉及个人信息、商业机密或未公开合作的内容，请改用其他渠道沟通。规则边界见<router-link to="/community-rules">《平台管理条例》</router-link>。
      </div>
    </section>
