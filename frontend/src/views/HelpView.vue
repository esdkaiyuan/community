      <h2>十三、通知管理</h2>
      <p>
        通知把与你有关的变化集中到一处，避免每天手动刷新项目页。平台目前有四类通知：参与、评论、回复与 @ 提及。
      </p>
      <h3>四类通知分别代表什么</h3>
      <ul>
        <li><strong>参与：</strong>有人参与了你发起的项目，或你参与的项目出现了新的参与者。</li>
        <li><strong>评论：</strong>你发起的项目收到了新的根评论。</li>
        <li><strong>回复：</strong>有人在你的评论下回复，或你在参与的讨论串里出现了新回复。</li>
        <li><strong>提及：</strong>有人在评论中用 @ 提到了你的用户名。</li>
      </ul>
      <h3>查看与处理</h3>
      <ol>
        <li>打开<router-link to="/notifications">通知页</router-link>，按时间从新到旧浏览。</li>
        <li>点击一条通知，会跳转到对应项目或评论位置。</li>
        <li>阅读后该条通知标记为已读，未读数量随之减少。</li>
        <li>积压较多时，可以使用全部已读，一次性清空未读状态。</li>
      </ol>
      <div class="doc-note">
        <strong>通知不是聊天工具。</strong>
        通知只提示「发生了什么」，具体沟通仍在评论区进行。平台没有私信功能，请不要在评论里留手机号、社交账号等联系方式，以免被无关的人收集。
      </div>
    </section>

