      <h3>3. 接口频率限制</h3>
      <p>
        登录、注册、找回密码等接口设有频率限制，用于减少暴力破解、验证码轰炸与批量注册。受保护项目的解锁校验也会记录失败行为，失败过多会触发限制。频率限制可能根据 IP、账号或设备特征综合判断，但不会因此长期保存额外的行为画像。若你正常操作却被误判，可以通过反馈渠道说明情况，我们会核查并调整。
      </p>

      <h3>4. 上传与内容校验</h3>
      <p>
        封面上传会校验 MIME 类型与文件头是否匹配，并限制文件大小为 5MB。这可以拦截一部分伪装成图片的可执行文件与超大文件，降低存储与解析风险。校验不能保证所有恶意文件都被识别，因此请不要上传来源不明的文件，也不要在项目描述中引导他人下载可疑程序。发现可疑内容时，可以通过反馈渠道提醒我们。
