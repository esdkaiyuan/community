      <h3>2. 密码与凭证</h3>
      <p>
        密码以 bcrypt 哈希保存，服务器不保存明文。bcrypt 的计算成本较高，能够增加批量破解的时间成本；每次哈希使用随机盐，降低彩虹表攻击的效果。修改密码后，令牌版本会提升，旧登录凭证立即失效。我们不会通过邮件、评论或私信向你索要密码；任何要求你提供密码的请求都应被视为可疑。
