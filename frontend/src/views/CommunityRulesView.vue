      <h2>九、广告、引流与商业化</h2>

      <h3>9.1 怎样识别广告</h3>
      <p>
        广告不一定带「广告」二字。判断标准包括：内容的主要目的是促成交易而非分享项目；反复出现价格、优惠、联系方式；以项目为壳，实际在卖课程、卖软件、卖服务；评论区集中出现同一销售话术。平台允许在项目介绍中说明合理成本与资助需求，但不允许把项目页变成商品详情页，也不允许用多个条目反复推销同一商品。
      </p>

      <h3>9.2 引流的常见形式</h3>
      <p>
        禁止在标题、封面、标签、评论中放置微信号、群号、网盘群、邀请码与短链；禁止以「资料包」「模板」「工具」为诱饵，要求先加好友再给内容；禁止用多个账号互相配合，把用户导流到站外。若确需提供补充材料，应使用仓库或公开文档链接，让所有浏览者都能平等获取。所谓「仅限粉丝」「私信领取」，通常就是引流的信号。
      </p>

      <h3>9.3 商业化的边界</h3>
      <p>
        平台不提供支付功能，不撮合交易，不担保项目真实性与合作结果。因此，任何需要付款、签约、投资、分成的安排，都应被视为当事人之间的独立行为，平台不参与也不背书。以平台名义承诺「官方合作」「平台担保」「平台返现」，属于虚假陈述，按冒充与诈骗处理。平台也不会因为项目出现在站内而对其质量作出任何暗示。
      </p>

      <h3>9.4 收费课程与服务</h3>
      <p>
        可以在项目中说明你提供付费咨询、培训或定制开发，但不得把项目页做成招生页：不得使用「限时名额」「最后一天」「不学就落后」等制造焦虑的话术；不得承诺保就业、保收益、保通过；不得把免费开源内容作为诱饵，再以付费解锁后续。面向初学者的收费内容，应清楚说明前置知识、交付形式与退款安排，并如实标注你自身的资历。
      </p>

      <h3>9.5 联盟链接与返利</h3>
      <p>
        使用联盟链接、返利链接时，应在显著位置说明该链接会为你带来收益。不得伪装成普通推荐；不得推荐你自己未验证的产品；不得把返利链接塞进开源项目的依赖说明中。以「公益」「免费」包装返利，属于误导。平台可能要求移除未披露的返利链接；反复隐瞒收益关系的账号，按广告违规处理。
      </p>
