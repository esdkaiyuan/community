      </p>

      <h3>3.2 字段填写规范</h3>
      <p>
        项目标题需 4 至 60 个字，应能概括项目主题，不得用纯符号、重复字符或与内容无关的热词堆砌。项目介绍需 20 至 2000 个字，少于 20 字无法说明任何有效信息，超过 2000 字应把细节放到仓库文档中。分类为必填项，只能选择技术开发、设计创意、产品/运营、内容创作、硬件/物联网、研究学习、开源专区、公益/社会创新之一。标签最多 5 个，单个不超过 12 个字。封面支持 JPG、PNG、WebP、GIF，大小不超过 5MB。
      </p>

      <h3>3.3 分类选择的常见错误</h3>
      <p>
        常见错误包括：把任何带代码的项目都放进「技术开发」，即使主体是视觉设计；把商业招募放进「公益/社会创新」以获取好感；把课程招生放进「研究学习」。分类影响浏览者的预期与推荐结果，错误分类会让真正需要的人找不到项目，也会让参与者带着错误预期进入。平台发现明显错分时会提示调整；同一账号反复错分、借分类获取不当曝光，按一般违规处理。
      </p>

      <h3>3.4 标签的使用</h3>
      <p>
        标签用于帮助检索，不是关键词堆砌场。应当选择能准确描述技术栈、领域与产出形态的词，例如具体语言、框架、应用场景。禁止把无关热门词全部塞进 5 个标签位；禁止使用与他人项目相同但无关的标签蹭流量；禁止在标签中出现联系方式、价格、引流话术或违规词。标签中出现站外联系方式，按广告引流处理；标签中出现违法内容，按内容底线处理。
      </p>

