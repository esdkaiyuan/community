      <p>
        封面应与项目内容相关，不得使用与项目无关的明星照片、影视截图、他人作品作为门面；不得在封面中放置二维码、微信号、群号、价格与「加我」字样；不得使用血腥、色情、惊悚或令人不适的图像；不得使用伪造的平台标识、官方认证标识与奖项图标。转载他人图片作封面，需取得授权或在项目介绍中标注来源与许可。
