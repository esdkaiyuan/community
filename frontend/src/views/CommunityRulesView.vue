        允许放置与项目直接相关的链接，例如代码仓库、项目主页、文档站点、演示地址、设计稿预览与许可证说明。链接应指向稳定的公开页面，不应要求登录后才能查看核心内容（加密项目按加密规则处理）。放置多个链接时，应说明每个链接的用途，避免浏览者误点。项目介绍中引用外部资料，也应注明它为什么与本项目相关。
      </p>

      <h3>5.5 禁止的链接类型</h3>
      <p>
        禁止短链跳转页、广告落地页、网盘下载页、博彩与色情站点、钓鱼页面、要求输入账号密码的仿冒页面；禁止以「加速」「镜像」「备用」为名指向不明站点；禁止使用会强制下载可执行文件的链接作为项目入口。链接指向的内容同样受本条例约束，不能因为「在站外」而免责。短链隐藏了真实去向，因此平台对短链的判断会更严格。
      </p>

      <h3>5.6 链接失效与维护</h3>
      <p>
        链接失效本身不算违规，但长期不维护会降低项目可信度。平台可能提示更新；若项目入口长期无法访问且无说明，浏览者可以举报。发起人应定期检查仓库是否公开、演示是否可用、许可证是否仍在。因链接被第三方接管而出现违规内容时，发起人应及时移除并说明情况，而不是保留链接等待他人自行辨别。
      </p>
