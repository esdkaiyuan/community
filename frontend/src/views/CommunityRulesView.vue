        你发布的项目介绍、评论、封面与标签，其著作权仍归你或原权利人所有；你授予平台在提供服务所必需的范围内展示、存储与传播的权利。这不意味着平台取得你的作品所有权，也不意味着平台可以把你的内容随意用于商业宣传。若内容包含他人作品，你必须确保自己有使用权，并在必要时标注作者、来源与许可证。
