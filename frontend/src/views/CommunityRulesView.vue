      <h2>十、发起人与参与者的责任</h2>

      <h3>10.1 发起人的职责</h3>
      <p>
        发起人自动成为参与者，且不能退出自己的项目。发起人应维护项目信息的准确性，及时更新进展与状态；对评论中的问题作出必要回应；在项目变更方向、延期或终止时说明原因。发起人不得以「共创」为名，要求参与者承担全部风险却不给出任何署名与说明；不得把参与者的成果据为己有。项目涉及他人资料时，发起人应确保已取得授权。
