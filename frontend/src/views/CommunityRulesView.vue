      <h3>7.2 转载与许可</h3>
      <p>
        转载他人文章、图片、代码、设计稿，应先确认许可证允许转载，并按要求保留署名与许可声明。标注「侵删」不等于获得授权；「仅用于学习」也不等于可以公开传播。CC 协议、开源许可证各有条件，例如署名、相同方式共享、非商业使用，必须逐条遵守。无法确认授权时，最安全的做法是链接原文而非复制全文，并在介绍中说明引用范围。
      </p>

      <h3>7.3 开源许可证的遵守</h3>
      <p>
        开源项目应明确写出所使用的许可证，并在仓库中包含许可证文件。以开源名义发布但实际限制他人使用、在许可证之外附加歧视性条款、把他人开源代码闭源后重新发布，都可能构成违规。平台不提供法律意见，但会在收到可核实的投诉时要求说明；屡次无视许可证的项目，可能被隐藏或删除。协议变化时，应保留变更记录。
      </p>

      <h3>7.4 商标与商业秘密</h3>
      <p>
        不得使用他人商标作为项目名称、封面标识或分类标签，造成来源混淆；不得发布通过不正当手段获取的商业秘密、内部文档、未公开的财务数据与客户名单。引用他人产品名称进行兼容性说明时，应使用描述性表述，避免暗示官方授权。涉及竞品分析时，应基于公开信息，不披露通过保密关系获得的内容。转载内部培训材料，同样可能构成侵权。
