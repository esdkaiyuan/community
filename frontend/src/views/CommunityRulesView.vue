      <h2>六、评论与互动规范</h2>

      <h3>6.1 两级评论结构下的表达</h3>
      <p>
        评论分为根评论与回复两级，回复之下不再嵌套。根评论每页显示 10 条，某条根评论下的回复超过 3 条时折叠显示。结构限制意味着：你无法通过无限嵌套把讨论引向别处，也不应把回复当作新的根评论反复开楼。想讨论新话题，应发起新的根评论；想回应某人，应使用回复。删除根评论会连带删除其下所有回复，删除前有确认框，请确认你愿意承担这一后果。
      </p>

      <h3>6.2 单条评论的长度与表达</h3>
      <p>
        单条评论不超过 500 字。超过时应拆分要点，或把详细论证放到项目仓库、文档中再链接回来。不要把长文切成多条连续回复刷屏；不要用大量重复字符、无意义符号、空白段落占据版面。表达观点可以强烈，但应让读者看懂你在回应哪句话、依据是什么。纯情绪宣泄、只贴标签不给理由的评论，在举报后可能被隐藏。
      </p>

      <h3>6.3 回复与@提及</h3>
      <p>
        回复应针对被回复的内容。@真实用户名会高亮并通知对方，因此@是一种打扰他人的行为，应仅在确有必要时使用：邀请对方补充信息、告知对方你的回应、指出对方可能关心的错误。禁止批量@无关用户、@全体、用@进行广告投放或施压。被@者没有义务立即回应；反复@同一人追问、在对方明确表示不愿继续后继续@，可能构成骚扰。
      </p>

      <h3>6.4 点赞的使用</h3>
      <p>
        点赞表达认可，不产生额外义务。禁止刷赞、互赞群、用脚本批量点赞、以点赞换取关注或密码。平台会根据行为模式识别异常点赞，例如短时间内对大量项目点赞、点赞与评论完全不匹配、多个账号同步操作。异常点赞可能被清除，相关账号可能被限制互动。点赞不是投票权，也不能用来施压发起人改变项目方向。
      </p>

      <h3>6.5 怎样算骚扰</h3>
      <p>
        满足下列任一情形即可认定为骚扰：对同一用户反复发送不受欢迎的针对性内容；在对方明确拒绝后继续纠缠；集中攻击外貌、性别、地域、疾病、家庭等与讨论无关的个人特征；威胁曝光隐私或线下报复；用大量小号围堵同一用户。判断时会看频率、持续性、是否被告知停止、是否存在多人协同。一次激烈争论不等于骚扰，持续针对同一个人的攻击才是。
      </p>

      <h3>6.6 刷屏、引战与冒充</h3>
      <p>
        刷屏指在同一项目下连续发布多条无实质内容或高度重复的评论，影响他人阅读；引战指故意挑起群体对立、地域攻击、性别对立，以获取回应而非解决问题；冒充指使用与发起人、参与者、平台官方高度相似的昵称或头像，暗示自己拥有某种身份或授权。冒充发起人尤其严重，因为它直接误导参与者对项目归属的判断，平台会优先处理并保存证据。
      </p>
    </section>

