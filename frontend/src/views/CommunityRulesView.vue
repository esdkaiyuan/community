      <h2>八、隐私、人肉与线下安全</h2>

      <h3>8.1 个人信息的边界</h3>
      <p>
        禁止发布他人的真实姓名、手机号、身份证号、住址、工作单位、家庭成员、病历、聊天记录与照片，除非取得本人明确同意且确有必要。项目协作中确需交换联系方式，应通过私下渠道，而不是写进公开的项目介绍与评论。公开场合只提供完成协作所必需的最少信息。即使信息来自公开渠道，也不代表可以随意拼接与集中发布。
      </p>

      <h3>8.2 人肉搜索</h3>
      <p>
        以「扒皮」「曝光」「求扩散」为名，收集、拼接、发布他人身份信息，即使信息来自公开渠道，只要目的是识别特定个人并对其造成压力，即构成人肉搜索。平台对这类内容零容忍：立即删除、限制功能、保存证据，情节严重的依法报告。参与转发、补充信息、提供线索的账号同样可能被处理。以「讨论公共事件」为名针对个人，也不构成豁免。
      </p>

      <h3>8.3 未成年人保护</h3>
      <p>
        涉及未成年人的内容需要更高标准的保护。禁止发布未成年人的清晰正面照、学校与住址、家庭情况；禁止以招募项目为名接触未成年人并索取隐私；禁止诱导未成年人参与高风险线下活动。面向未成年人的项目应说明监护与安全安排。发现疑似侵害未成年人的内容，应立即举报，不要自行扩散或进行取证式传播，后者可能造成二次伤害。
      </p>

      <h3>8.4 线下协作的安全</h3>
      <p>
        平台不组织线下活动，也不审核线下见面的安全性。参与者决定线下见面时，应选择公共场所、告知亲友行程、避免单独前往陌生地点、不携带大量现金。发起人不应要求参与者在未充分沟通的情况下前往异地或提供证件原件。若在协作中遭遇威胁、跟踪或骚扰，应保留证据并向平台与当地有关部门反映，不要以公开曝光代替求助。
      </p>

      <h3>8.5 信息泄露的应急处理</h3>
      <p>
