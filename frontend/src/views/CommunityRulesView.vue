      <h3>4.1 加密项目是什么、不是什么</h3>
      <p>
        加密项目是平台提供的一种访问控制选项：「仓库级」只隐藏仓库地址，「项目级」隐藏介绍、标签、仓库地址与共创伙伴，标题、封面与分类仍然公开。密码长度为 6 至 64 位，由发起人自行设置；同一时间每账号最多只能有 1 个加密项目。平台不保管明文密码，也不提供密码代管、代发或找回服务；发起人始终可以看到自己的项目。加密是一种缩小公开范围的工具，不是隐身衣，也不改变内容必须合法这一前提。
      </p>

      <h3>4.2 不得借加密藏匿违法内容</h3>
      <p>
        加密只改变可见范围，不改变责任。以下行为一律禁止：把违法、色情、诈骗、侵权内容放进加密项目，认为「反正别人看不到」；用加密项目的标题与封面暗示违法交易，把具体内容藏在密码之后；把加密项目当作私密群组，在其中组织传销、赌博或非法集资。平台在收到可核实的举报后，可以要求发起人说明，必要时在合规范围内核查；拒绝说明或说明与事实不符的，按严重违规处理。
      </p>

      <h3>4.3 不得诱导付费解锁</h3>
      <p>
        禁止以「付费后给密码」「打赏进群」「购买课程送项目密码」等方式，把加密项目变成付费墙。判断标准是：是否存在以金钱、虚拟礼物、关注、转发为条件换取访问权限的安排；是否在公开的标题、封面或评论中反复暗示付费可得。平台不提供支付能力，也不撮合任何交易，因此这类安排一旦发生，风险完全由当事人承担，平台同时会按诱导付费与广告引流处理相关内容。
      </p>

      <h3>4.4 不得公开他人密码、不得规避审核</h3>
      <p>
        未经发起人同意公开其加密项目密码，属于侵犯他人对内容的控制权，按严重违规处理；由此造成的泄露与损失，由公开者承担相应责任。也不得通过技术手段绕过密码校验、抓取加密内容、批量试错猜解密码，或把加密内容转载到站外。规避审核同样禁止：以加密为名发布会被正常审核拦截的内容，或使用变体词、图片文字、拼音缩写绕开检测。
      </p>

      <h3>4.5 密码保管责任</h3>
      <p>
        密码由发起人自行保管，平台不保存明文，因此平台无法帮你找回密码。建议在本地记录，并避免使用与账号密码相同的字符串。若怀疑密码已泄露，应立即修改，并检查项目内容是否被外传。因发起人泄露密码、在公开渠道张贴密码或在评论中发送密码而导致的访问扩散，不属于平台责任。发起人始终可见自己的项目，这一点不会因密码问题而改变。
      </p>

      <h3>4.6 加密项目的举报与核查</h3>
      <p>
        举报加密项目时，举报人通常看不到内部内容，因此需要提供足以定位的证据，例如公开可见的标题、封面、评论中的可疑表述，或站外截图与时间线。平台会据此判断是否需要进一步核查，并在不扩大泄露范围的前提下处理。举报人不应当为了取证而公开他人密码或传播加密内容，这样做本身可能构成违规。发起人对核查要求的合理说明，也是加密项目合规的一部分。
