      <p>
        参与者可以随时停止投入，但应告知发起人已完成的部分与未完成的部分，避免留下无法交接的工作。退出后，已提交并被采纳的代码、设计与文稿，其使用范围按事前约定或原有许可证处理；未约定时，建议双方以书面方式补充确认。发起人不得因参与者退出而删除其署名，参与者也不得撤回已明确授权使用的成果，除非约定中另有安排。
