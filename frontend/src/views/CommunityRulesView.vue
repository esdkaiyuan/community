      <h3>7.5 侵权投诉的处理</h3>
      <p>
        权利人投诉时，应提供权属证明、侵权内容定位与必要的比对说明。平台会先通知发布者，给予合理时间回应；发布者可提交授权证明、许可截图或反驳理由。对明显侵权且无法提供授权的，平台删除或隐藏内容；对争议较大的，可能先限制展示范围，待双方补充材料后再判断。重复侵权会导致功能限制乃至账号终止。
      </p>

      <h3>7.6 二次创作与衍生作品</h3>
      <p>
        在他人作品基础上做翻译、改编、移植、重构，属于二次创作，应遵守原作品许可证对衍生作品的要求。常见错误包括：只在末尾写一句「灵感来源」，却不说明具体使用了哪些部分；把他人项目整体改写后当作原创；删除原有的署名与版权声明；在禁止商用的许可证下发布付费版本。判断是否构成合理引用，关键看使用比例、替代性与是否影响原作品的市场。
      </p>
